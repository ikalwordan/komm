const FONT_INDEX = (() => { const m = {}; for (let i = 0; i < FONT_CHARS.length; i++) m[FONT_CHARS[i]] = i; return m; })();

// draw one string of the 5x7 font; advance is 6*scale per char (matches drawTextN)
function fontDraw(ctx, x, y, scale, css, str) {
  ctx.fillStyle = css;
  let cx = x;
  for (let i = 0; i < str.length; i++) {
    let ch = str[i];
    if (ch >= "a" && ch <= "z") ch = String.fromCharCode(ch.charCodeAt(0) - 32); // fold lowercase -> uppercase, matching PSP font.c glyphFor()
    const gi = FONT_INDEX[ch];
    if (gi !== undefined) {
      const g = FONT_GLYPHS[gi];
      for (let r = 0; r < 7; r++)
        for (let b = 0; b < 5; b++)
          if (g[r] & (0x10 >> b))
            ctx.fillRect(cx + b * scale, y + r * scale, scale, scale);
    }
    cx += 6 * scale;
  }
}
function fontWidth(str, scale) { return str.length ? str.length * 6 * scale - scale : 0; }
